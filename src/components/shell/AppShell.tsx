import { Bell, ChartLine, FlaskConical, House, Info, type LucideIcon } from 'lucide-react'
import { useState } from 'react'
import { AboutView } from '@/components/about/AboutView'
import { InsightsView } from '@/components/insights/InsightsView'
import { MonitorView } from '@/components/monitor/MonitorView'
import { SettingsSheet } from '@/components/monitor/SettingsSheet'
import { TestsView } from '@/components/tests/TestsView'
import { useAlertFeedback } from '@/hooks/useAlertFeedback'
import type { PostureModel } from '@/hooks/usePostureEngine'
import { cn } from '@/lib/cn'
import { AlertBanner } from './AlertBanner'

export type Tab = 'monitor' | 'insights' | 'tests' | 'about'

const TABS: Array<{ id: Tab; label: string; icon: LucideIcon }> = [
  { id: 'monitor', label: 'Monitor', icon: House },
  { id: 'insights', label: 'Insights', icon: ChartLine },
  { id: 'tests', label: 'Tests', icon: FlaskConical },
  { id: 'about', label: 'About', icon: Info },
]

function Logo() {
  return (
    <svg viewBox="0 0 48 48" aria-hidden className="size-11">
      <circle cx="24" cy="24" r="24" fill="var(--color-sun)" />
      <path d="M24 11v26" stroke="var(--color-ink)" strokeWidth="3.5" strokeLinecap="round" />
      <circle cx="24" cy="11.5" r="3.5" fill="var(--color-ink)" />
      <path d="M15 27c3 2.5 6 3.5 9 3.5s6-1 9-3.5" stroke="var(--color-ink)" strokeWidth="3" fill="none" strokeLinecap="round" />
    </svg>
  )
}

interface AppShellProps {
  model: PostureModel
  /** Controlled tab, used by the demo recording. */
  tab?: Tab
  onTabChange?(tab: Tab): void
  className?: string
}

export function AppShell({ model, tab: controlledTab, onTabChange, className }: AppShellProps) {
  const [ownTab, setOwnTab] = useState<Tab>('monitor')
  const tab = controlledTab ?? ownTab
  const setTab = (next: Tab) => {
    setOwnTab(next)
    onTabChange?.(next)
  }
  const [settingsOpen, setSettingsOpen] = useState(false)
  const posture = model.state.engine.postureState
  const alert = useAlertFeedback(posture, model.soundOn, model.state.running)
  const unseenAlerts = model.state.stats.alerts

  return (
    <div className={cn('min-h-dvh bg-ink pb-32 text-paper', className)}>
      <AlertBanner visible={alert.visible} seconds={model.state.latest?.persistenceSeconds ?? 0} onDismiss={alert.dismiss} />

      <header className="mx-auto flex max-w-6xl items-center justify-between gap-3 px-4 pt-[max(16px,env(safe-area-inset-top))] sm:px-6">
        <div className="flex items-center gap-3">
          <Logo />
          <div>
            <h1 className="text-xl font-medium leading-none">AlignMe</h1>
            <p className="mt-1 text-xs text-mist">Posture monitor</p>
          </div>
        </div>
        <div className="flex items-center gap-2">
          <span className="rounded-full border border-sun/40 px-3 py-1.5 text-xs text-sun" title="All readings are generated by the simulator, not measured by hardware">
            Simulated data
          </span>
          <button
            type="button"
            onClick={() => setTab('insights')}
            aria-label={`Open insights, ${unseenAlerts} alerts this session`}
            className="relative grid size-12 place-items-center rounded-full bg-graphite hover:bg-graphite-2"
          >
            <Bell aria-hidden className="size-5 text-sun" />
            {unseenAlerts > 0 && (
              <span className="absolute -right-0.5 -top-0.5 grid min-w-5 place-items-center rounded-full bg-coral px-1 text-[11px] font-medium text-ink">
                {unseenAlerts}
              </span>
            )}
          </button>
        </div>
      </header>

      <main className="mx-auto mt-5 max-w-6xl px-4 sm:px-6">
        {tab === 'monitor' && <MonitorView model={model} onOpenSettings={() => setSettingsOpen(true)} />}
        {tab === 'insights' && <InsightsView model={model} />}
        {tab === 'tests' && <TestsView />}
        {tab === 'about' && <AboutView storageStatus={model.storageStatus} />}
      </main>

      <nav aria-label="Sections" className="fixed inset-x-0 bottom-0 z-40 flex justify-center px-4 pb-[max(14px,env(safe-area-inset-bottom))]">
        <ul className="flex w-full max-w-md items-center justify-around rounded-[32px] bg-graphite/95 px-2 py-2 shadow-2xl shadow-black/60 backdrop-blur">
          {TABS.map(({ id, label, icon: Icon }) => {
            const active = tab === id
            return (
              <li key={id}>
                <button
                  type="button"
                  onClick={() => setTab(id)}
                  aria-label={label}
                  aria-current={active ? 'page' : undefined}
                  className={cn('flex flex-col items-center gap-1 rounded-3xl px-4 py-2 text-[11px] transition', active ? 'text-sun' : 'text-mist hover:text-paper')}
                >
                  <Icon aria-hidden className="size-6" strokeWidth={active ? 2.2 : 1.7} />
                  <span>{label}</span>
                </button>
              </li>
            )
          })}
        </ul>
      </nav>

      <SettingsSheet model={model} open={settingsOpen} onClose={() => setSettingsOpen(false)} />
    </div>
  )
}
